-- สิ่งที่ต้องทำนอกเหนือจากไฟล์นี้
--
-- ก) ปิดพอร์ต 3306 ที่ไฟร์วอลล์ของผู้ให้บริการ ให้เปิดเฉพาะ IP โรงงาน
--    นี่คือด่านที่สำคัญที่สุด สำคัญกว่าการจำกัด host ใน MySQL เอง
--    เพราะกันตั้งแต่ก่อนถึงชั้นตรวจรหัสผ่าน
--    Hostinger VPS: ufw allow from <ip> to any port 3306
--    Railway: ไม่มีไฟร์วอลล์ระดับ IP -- ถ้าจะใช้ Railway ต้องยอมรับว่า
--             พอร์ตเปิดสาธารณะ โดยมีแค่รหัสสั้น ๆ กั้น ซึ่ง **ไม่ควรยอมรับ**
--
-- ข) บัญชีผู้ดูแลจริงต้องเป็นคนละตัว ชื่ออื่น รหัสแข็ง และจำกัด host ต่างหาก
--    บัญชีตัวนี้มีไว้ให้ TruckScale เท่านั้น
--
-- ค) เปิด general log หรือ audit ช่วงแรกหลังย้าย เพื่อดูว่ามีใครพยายามต่อเข้ามาบ้าง
--
-- ง) สำรองฐานทุกวัน -- ย้ายขึ้นคลาวด์แล้วโรงงานไม่มีสำเนาในมืออีกต่อไป
--
-- IP ไม่คงที่
--   ถ้าโรงงานได้ IP ไม่คงที่ มีสองทาง
--   1. ขอ IP คงที่จากผู้ให้บริการอินเทอร์เน็ต -- ง่ายและถูกที่สุด แนะนำทางนี้
--   2. ตั้ง DDNS แล้วให้สคริปต์ที่ฝั่งคลาวด์อ่านชื่อโดเมนทุก 5 นาที
--      แล้วอัปเดตกฎไฟร์วอลล์ตาม  (MySQL เองรับชื่อโฮสต์ในช่อง host ได้
--      แต่ต้องปิด skip-name-resolve ซึ่งทำให้ทุกการเชื่อมต่อช้าลง จึงไม่แนะนำ)
