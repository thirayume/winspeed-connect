-- เตรียมบัญชีบน MySQL คลาวด์ให้ TruckScale ต่อได้ โดยจำกัดความเสียหายให้น้อยที่สุด
--
-- ที่มาของข้อจำกัด
--   WorldFerth.exe ฝังสตริงนี้ไว้ในไบนารี แก้ไม่ได้
--       DSN=TruckScales;UID=<ผู้ใช้>;PWD=<รหัส>
--   ทดสอบแล้วยืนยันว่า UID/PWD ในสตริง **ทับ** ค่าที่ตั้งไว้ใน DSN
--   จึงเลี่ยงไม่ได้ที่ฐานปลายทางต้องมีบัญชีชื่อและรหัสตรงกับที่ฝังไว้
--   รหัสจริงสั้นและเดาง่ายมาก จึงต้องล้อมด้วยมาตรการอื่นทั้งหมดข้างล่างนี้
--
--   ดูค่าจริงที่โปรแกรมฝังไว้ (อย่า commit ผลลัพธ์ลง repo สาธารณะ):
--       .\Set-TruckScaleDSN.ps1 -TestOnly    <- อ่านจาก exe ให้เอง
--
--   สิ่งที่ทำได้คือทำให้บัญชีนั้น "ชื่อ root แต่ไม่ใช่ root"
--     - ให้สิทธิ์แค่ DML บนฐานเดียว ไม่มี DDL ไม่มีสิทธิ์ระดับเซิร์ฟเวอร์
--     - บังคับ TLS
--     - จำกัด host ให้ต่อได้จาก IP ของโรงงานเท่านั้น
--     - จำกัดจำนวนการเชื่อมต่อ กันการเดารหัสแบบรัว
--
-- ใช้คู่กับ Set-TruckScaleDSN.ps1 (ฝั่งเครื่องลูกข่าย)
-- ========================================================================

-- ------------------------------------------------------------------------
-- 1) แก้ IP ตรงนี้ก่อนรัน
--    ใส่ IP สาธารณะของโรงงาน ห้ามใช้ '%' บนฐานที่เปิดออกอินเทอร์เน็ต
--    ถ้าโรงงานเป็น IP ไม่คงที่ ให้ดูหัวข้อ "IP ไม่คงที่" ท้ายไฟล์
-- ------------------------------------------------------------------------
SET @plant_ip = '203.0.113.10';       -- <<<< IP สาธารณะของโรงงาน
SET @db       = 'db_truckscale';
SET @ts_user  = 'root';               -- <<<< ตามที่ฝังในไบนารี
SET @ts_pwd   = 'PUT-EMBEDDED-PWD-HERE';  -- <<<< ตามที่ฝังในไบนารี ห้าม commit ค่าจริง

-- ------------------------------------------------------------------------
-- 2) สร้างบัญชี
--    MAX_USER_CONNECTIONS กันเครื่องลูกข่ายค้างจนกินการเชื่อมต่อหมด
--    และทำให้การเดารหัสแบบรัวช้าลงมาก
-- ------------------------------------------------------------------------
SET @sql = CONCAT('DROP USER IF EXISTS ''', @ts_user, '''@''', @plant_ip, '''');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;

SET @sql = CONCAT(
  'CREATE USER ''', @ts_user, '''@''', @plant_ip, ''' ',
  'IDENTIFIED BY ''', @ts_pwd, ''' ',
  'REQUIRE SSL ',
  'WITH MAX_USER_CONNECTIONS 40 ',
  'FAILED_LOGIN_ATTEMPTS 20 PASSWORD_LOCK_TIME 1');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;

-- ------------------------------------------------------------------------
-- 3) ให้สิทธิ์เท่าที่โปรแกรมต้องใช้จริง
--    TruckScale อ่านและเขียนข้อมูลชั่ง แต่ไม่เคยสร้างหรือลบตาราง
--    ไม่ให้ DROP / ALTER / CREATE / GRANT / FILE / SUPER
-- ------------------------------------------------------------------------
SET @sql = CONCAT('GRANT SELECT, INSERT, UPDATE, DELETE ON `', @db, '`.* ',
                  'TO ''', @ts_user, '''@''', @plant_ip, '''');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;

FLUSH PRIVILEGES;

-- ------------------------------------------------------------------------
-- 4) ตรวจผล
-- ------------------------------------------------------------------------
SELECT user, host, ssl_type, max_user_connections
  FROM mysql.user
 WHERE user = @ts_user;

SET @sql = CONCAT('SHOW GRANTS FOR ''', @ts_user, '''@''', @plant_ip, '''');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;

