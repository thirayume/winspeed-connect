
-- Emergency password reset for one Sale-App account on R740.
-- SSMS: connect to R740-SRV\SQL2008 and select the intended database.
-- First run with @Apply = 0, review the account, then run with @Apply = 1.
-- Generate a bcrypt cost-12 hash with New-Uat2AdminSql.ps1 -HashOnly.
-- Never put a plaintext password into SQL.

SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET ARITHABORT ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET QUOTED_IDENTIFIER ON;
SET NUMERIC_ROUNDABORT OFF;
GO

DECLARE @ExpectedDatabase sysname = N'';       -- dbwins_worldfert9 or dbwins_worldfert9_uat
DECLARE @Username nvarchar(128) = N'';        -- exact Sale-App username
DECLARE @PasswordHash nvarchar(255) = N'';    -- fill before apply
DECLARE @Apply bit = 0;

IF ISNULL(CONVERT(nvarchar(128), SERVERPROPERTY('ServerName')), N'') COLLATE Latin1_General_BIN2
       <> N'R740-SRV\SQL2008'
   OR @ExpectedDatabase IS NULL
   OR @ExpectedDatabase COLLATE Latin1_General_BIN2 NOT IN (N'dbwins_worldfert9', N'dbwins_worldfert9_uat')
   OR DB_NAME() COLLATE Latin1_General_BIN2 <> @ExpectedDatabase COLLATE Latin1_General_BIN2
BEGIN
    RAISERROR('Wrong SQL instance or database. Select the intended R740 database.', 16, 1);
    RETURN;
END;

IF @Username IS NULL OR LEN(@Username) NOT BETWEEN 1 AND 50 OR DATALENGTH(@Username) <> DATALENGTH(LTRIM(RTRIM(@Username)))
BEGIN
    RAISERROR('Specify one exact Sale-App username without surrounding spaces.', 16, 1);
    RETURN;
END;

IF @Apply = 1 AND (
       @PasswordHash IS NULL
       OR DATALENGTH(@PasswordHash) <> 120
       OR LEFT(@PasswordHash, 7) COLLATE Latin1_General_BIN2 <> N'$2b$12$'
       OR SUBSTRING(@PasswordHash, 8, 53) COLLATE Latin1_General_BIN2 LIKE N'%[^./0-9A-Za-z]%'
   )
BEGIN
    RAISERROR('Enter a complete bcrypt cost-12 hash generated by the supplied helper.', 16, 1);
    RETURN;
END;

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @AccountId int;
    DECLARE @Count int;
    SELECT @Count = COUNT(*), @AccountId = MIN(Id)
    FROM wf.AppUser WITH (UPDLOCK, HOLDLOCK)
    WHERE Username COLLATE Latin1_General_BIN2 = @Username COLLATE Latin1_General_BIN2
      AND IsActive = 1;

    IF @Count <> 1
        RAISERROR('The exact username must match one active Sale-App account.', 16, 1);

    IF @Apply = 1
    BEGIN
        UPDATE wf.AppUser
        SET PasswordHash = @PasswordHash, MustChangePassword = 1, UpdatedAt = GETUTCDATE()
        WHERE Id = @AccountId;

        IF @@ROWCOUNT <> 1
            RAISERROR('Expected to update exactly one account.', 16, 1);
    END;

    SELECT DB_NAME() AS DatabaseName, Id, Username, DisplayName, Role, MustChangePassword,
           CASE WHEN @Apply = 1 THEN N'APPLIED' ELSE N'PREVIEW' END AS Result
    FROM wf.AppUser
    WHERE Id = @AccountId;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    DECLARE @ErrorMessage nvarchar(2048) = ERROR_MESSAGE();
    RAISERROR(N'%s', 16, 1, @ErrorMessage);
END CATCH;
